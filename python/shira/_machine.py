def bands(name: str, machine: str | None = None, cpu_class: str | None = None, family: str | None = None) -> Bands:
    assert name in DEFAULT, name
    m = _threads.MACHINE if machine is None else machine
    c = CPU_CLASS if cpu_class is None else cpu_class
    f = FAMILY if family is None else family
    for key in (m, c, f):
        row = TABLE.get(key, {})
        if name in row:
            return row[name]
    return DEFAULT[name]


def value(name: str, features: int, machine: str | None = None, cpu_class: str | None = None,
          family: str | None = None) -> int:
    assert features >= 1
    b = bands(name, machine, cpu_class, family)
    assert b and b[-1][0] == OPEN, name
    for top, val in b:
        if features <= top:
            return int(val)
    return int(b[-1][1])
